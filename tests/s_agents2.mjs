export default async (p) => {
  // Agent A: edit a file + run a command (needs approval)
  await p.fill('.aw-pane .composer-input', 'Add a header comment to src/todo.js then run `npm test`')
  await p.keyboard.press('Enter')
  // Agent B in parallel (split layout)
  await p.click('button[title="Side by side (2 agents)"]')
  await p.click('.aw-tab-add')
  await p.waitForTimeout(300)
  await p.fill('.aw-pane.focused .composer-input', 'Create src/greet.js with a hello function, make a plan todo')
  await p.keyboard.press('Enter')
  await p.waitForSelector('.needs-approval', { timeout: 20000 })
  await p.waitForTimeout(500)
  await p.screenshot({ path: 'tests/screens/agents2a.png' })
  await p.click('.needs-approval button.btn-primary')
  await p.waitForFunction(() => document.querySelectorAll('.aw-item .st-done').length >= 2, null, { timeout: 30000 })
  await p.waitForTimeout(500)
  await p.click('.aw-pane:first-child .changes-head button:has-text("Review")')
  await p.waitForTimeout(1200)
}
