export default async (p) => {
  await p.click('.tree-row[data-path="src"]').catch(()=>{})
  await p.waitForTimeout(200)
  if (!(await p.$('.tree-row[data-path="src/todo.js"]'))) await p.click('.tree-row[data-path="src"]')
  await p.dblclick('.tree-row[data-path="src/todo.js"]')
  await p.waitForTimeout(400)
  await p.dblclick('.tree-row[data-path="README.md"]')
  await p.waitForTimeout(300)
  await p.click('.tab:has-text("todo.js")')
  await p.waitForTimeout(300)
  await p.click('.monaco-editor .view-lines')
  await p.keyboard.press('Control+End')
  await p.keyboard.type('\n// hello')
  await p.keyboard.press('Control+`')
  await p.waitForTimeout(300)
  await p.keyboard.type('ls src && cat package.json')
  await p.keyboard.press('Enter')
  await p.waitForTimeout(1200)
}
