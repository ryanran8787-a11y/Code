// E2E for v2 features: PTY terminal, Source Control, worktree-isolated parallel
// agents, background processes + integrated browser + Design Mode, @-mentions,
// context meter / compaction. Uses the built-in mock model.
import { chromium } from 'playwright'
import fs from 'node:fs'
import { execSync } from 'node:child_process'
const TOKEN = process.env.ACCESS_TOKEN || (/ACCESS_TOKEN=(.*)/.exec(fs.existsSync('.env.local') ? fs.readFileSync('.env.local', 'utf8') : '') || [])[1] || ''
const BASE = process.env.BASE || 'http://localhost:3000'
const WS = 'workspace'
const ok = (c, m) => { if (!c) throw new Error('ASSERT: ' + m); console.log('  ✓ ' + m) }
const api = (path, method = 'GET', body) => fetch(BASE + path, { method, headers: { 'content-type': 'application/json', cookie: 'cw_token=' + TOKEN }, body: body && JSON.stringify(body) }).then((r) => r.json())
const shot = (p, n) => p.screenshot({ path: `tests/screens/v2-${n}.png` })

await api('/api/settings', 'PUT', { baseUrl: 'mock', autoRunCommands: true, defaultEnv: 'local' })
for (const a of await api('/api/agents')) await api('/api/agents/' + a.id, 'DELETE')
for (const p of await api('/api/processes')) await api('/api/processes/' + p.id, 'DELETE')
for (const t of await api('/api/terminals')) await api('/api/terminals/' + t.id, 'DELETE')
execSync(`git -C ${WS} checkout -q . && git -C ${WS} clean -fdq`)
const todoOrig = fs.readFileSync(`${WS}/src/todo.js`, 'utf8')

const b = await chromium.launch()
const p = await b.newPage({ viewport: { width: 1440, height: 860 } })
const errors = []
p.on('pageerror', (e) => errors.push(e.message))
await p.addInitScript(() => { if (!sessionStorage.getItem('x')) { localStorage.clear(); sessionStorage.setItem('x', '1') } })
await p.goto(BASE + '/?token=' + TOKEN + '#editor')
await p.waitForSelector('.app')

console.log('1. Interactive PTY terminal')
await p.keyboard.press('Control+`')
await p.waitForSelector('.xterm-host .xterm-rows', { timeout: 15000 })
await p.waitForTimeout(800)
await p.click('.xterm-host')
await p.keyboard.type('echo PTY_$((6*7)) && cd src && pwd\n')
await p.waitForFunction(() => document.querySelector('.xterm-rows')?.textContent.includes('PTY_42'), null, { timeout: 10000 })
ok(true, 'command typed into xterm executed in a real shell (PTY_42)')
await p.keyboard.type('python3 -c "import sys; print(\'TTY\', sys.stdin.isatty())"\n')
await p.waitForFunction(() => document.querySelector('.xterm-rows')?.textContent.includes('TTY True'), null, { timeout: 10000 })
ok(true, 'terminal is a real TTY (interactive programs work)')
await p.click('.panel-title button[title="New Terminal"]')
await p.waitForFunction(() => document.querySelectorAll('.term-item').length === 2, null, { timeout: 8000 })
ok(true, 'second terminal created, terminal list shown')
await shot(p, 'terminal')

console.log('2. Source Control')
fs.writeFileSync(`${WS}/src/todo.js`, todoOrig.replace('this.items = []', 'this.items = [] // edited'))
const NOTE = `NOTES-${Date.now()}.md`
fs.writeFileSync(`${WS}/${NOTE}`, '# notes\n')
await p.keyboard.press('Control+Shift+G')
await p.waitForSelector('.scm-row', { timeout: 8000 })
const rows = await p.$$eval('.scm-row', (els) => els.map((e) => e.textContent))
ok(rows.some((r) => r.includes('todo.js')) && rows.some((r) => r.includes(NOTE)), 'modified + untracked files listed')
await p.click('.scm-row:has-text("todo.js")')
await p.waitForSelector('.tab.active:has-text("todo.js") .tab-desc:has-text("Working Tree")')
ok(true, 'clicking a change opens HEAD ↔ working tree diff')
await p.hover(`.scm-row:has-text("${NOTE}")`)
await p.click(`.scm-row:has-text("${NOTE}") button[title="Stage"]`)
await p.waitForSelector('.scm-group-head:has-text("Staged Changes")')
ok(true, 'stage moves file to Staged Changes')
await p.fill('.scm-msg', 'Add notes')
await p.click('.scm-commit-btn')
await p.waitForFunction(() => [...document.querySelectorAll('.scm-commit-row')].some((r) => r.textContent.includes('Add notes')), null, { timeout: 8000 })
ok(execSync(`git -C ${WS} log -1 --pretty=%s`).toString().trim() === 'Add notes', 'commit created in git')
await shot(p, 'scm')
execSync(`git -C ${WS} checkout -q src/todo.js`)

console.log('3. Parallel agents in isolated git worktrees')
await p.keyboard.press('Control+Shift+A')
await p.waitForSelector('.agents-window:not(.hidden)')
await p.click('button[title="Side by side (2 agents)"]')
for (const [i, prompt] of ['Please edit src/todo.js', 'Please edit src/todo.js and src/utils.js'].entries()) {
  if (i) { await p.click('.aw-tab-add'); await p.waitForTimeout(150) }
  const env = await p.textContent('.aw-pane.focused .env-pill')
  if (!env.includes('Worktree')) await p.click('.aw-pane.focused .env-pill')
  await p.fill('.aw-pane.focused .composer-input', prompt)
  await p.keyboard.press('Enter')
  await p.waitForTimeout(300)
}
await p.waitForFunction(() => document.querySelectorAll('.aw-item .st-done').length >= 2, null, { timeout: 30000 })
const agents = await api('/api/agents')
ok(agents.filter((a) => a.env === 'worktree').length === 2 && new Set(agents.map((a) => a.branch)).size === 2, 'two agents, each on its own agent/* branch')
ok(fs.readFileSync(`${WS}/src/todo.js`, 'utf8') === todoOrig, 'main workspace untouched while agents work in worktrees')
const wts = execSync(`git -C ${WS} worktree list`).toString().trim().split('\n')
ok(wts.length === 3, 'git shows 2 extra worktrees')
await p.waitForSelector('.aw-pane .wt-badge')
if (await p.isHidden('.aw-review')) await p.click('.aw-layout-btns button[title^="Toggle Review Panel"]')
await p.click('.aw-review .aw-rtab:has-text("Changes")')
await p.waitForSelector('.aw-wt-bar', { timeout: 8000 }).catch(async (e) => { await shot(p, 'fail'); throw e })
await shot(p, 'worktrees')
const a1 = agents.find((a) => a.title === 'Please edit src/todo.js')
await api(`/api/agents/${a1.id}/changes/resolve`, 'POST', { accept: true })
ok(fs.readFileSync(`${WS}/src/todo.js`, 'utf8').startsWith('// Edited by the mock agent'), 'Apply merges worktree changes into the main workspace')
const a2 = agents.find((a) => a.id !== a1.id)
const r2 = await fetch(`${BASE}/api/agents/${a2.id}/changes/resolve`, { method: 'POST', headers: { 'content-type': 'application/json', cookie: 'cw_token=' + TOKEN }, body: JSON.stringify({ accept: true }) }).then((r) => r.json())
ok(!r2.error && fs.readFileSync(`${WS}/src/utils.js`, 'utf8').startsWith('// Edited by the mock agent'), 'second agent applied too (identical overlapping edit in todo.js is not a conflict)')
execSync(`git -C ${WS} checkout -q src/todo.js src/utils.js`)
const a3 = (await api('/api/agents', 'POST', { prompt: 'Please edit src/todo.js', env: 'worktree' }))
await new Promise((r) => setTimeout(r, 2500))
// user edits the main workspace *after* the agent forked -> real divergence
fs.writeFileSync(`${WS}/src/todo.js`, todoOrig.replace('pending() {', 'pendingItems() {'))
const r3 = await fetch(`${BASE}/api/agents/${a3.id}/changes/resolve`, { method: 'POST', headers: { 'content-type': 'application/json', cookie: 'cw_token=' + TOKEN }, body: JSON.stringify({ accept: true }) }).then((r) => r.json())
ok(fs.readFileSync(`${WS}/src/todo.js`, 'utf8').includes('pendingItems') && fs.readFileSync(`${WS}/src/todo.js`, 'utf8').includes('Edited by the mock agent'), '3-way merge combines agent edit with a divergent user edit' + (r3.error ? ' (' + r3.error + ')' : ''))
await api('/api/agents/' + a3.id, 'DELETE')

console.log('4. Background process + integrated browser + Design Mode')
fs.mkdirSync(`${WS}/site`, { recursive: true })
fs.writeFileSync(`${WS}/site/index.html`, '<!doctype html><html><head><title>Demo</title><link rel="stylesheet" href="/style.css"></head><body><h1 id="hero">Hello Preview</h1><button id="cta">Buy now</button></body></html>')
fs.writeFileSync(`${WS}/site/style.css`, 'h1{color:rgb(255, 99, 71)}')
await p.click('button[title="Single agent"]')
await p.click('.aw-new')
if ((await p.textContent('.aw-pane .env-pill')).includes('Worktree')) await p.click('.aw-pane .env-pill')
await p.fill('.aw-pane .composer-input', 'serve the site folder on port 5188 and preview it')
await p.keyboard.press('Enter')
await p.waitForSelector('.aw-pane .port-chip:has-text("5188")', { timeout: 20000 })
ok(true, 'agent started a background server; detected port shown on the tool card')
await p.waitForSelector('.aw-pane .tool-line:has-text("localhost:5188") .exit-ok', { timeout: 15000 })
ok(true, 'agent verified the page with fetch_url (HTTP 200)')
await p.click('.aw-pane .port-chip:has-text("5188")')
await p.waitForSelector('.aw-review .browser-frame')
const frame = await (await p.waitForSelector('.aw-review .browser-frame')).contentFrame()
await frame.waitForSelector('#hero', { timeout: 10000 })
ok((await frame.$eval('#hero', (e) => getComputedStyle(e).color)) === 'rgb(255, 99, 71)', 'integrated browser renders page + CSS through the proxy')
await p.click('.aw-review button[title^="Design Mode"]')
await p.waitForTimeout(300)
await frame.click('#cta')
await p.waitForSelector('.design-card:not(.hidden)', { timeout: 5000 })
ok((await p.textContent('.design-card code')).includes('#cta'), 'Design Mode picked element selector #cta')
await p.fill('.design-note', 'make this button larger')
await shot(p, 'design')
await p.click('.design-card .btn-primary')
const composed = await p.inputValue('.aw-pane .composer-input')
ok(composed.includes('#cta') && composed.includes('make this button larger'), 'structured design request placed in agent composer')
await p.fill('.aw-pane .composer-input', '')

console.log('5. @-mentions (files / folders / symbols) and context meter')
await p.click('.aw-new')
await p.click('.aw-pane .composer-input')
await p.keyboard.type('explain @Todo')
await p.waitForSelector('.mention-menu .mm-item', { timeout: 5000 })
await p.waitForSelector('.mention-menu .mm-sep:has-text("Symbols")', { timeout: 5000 })
ok(true, 'mention popup lists symbols (TodoList class)')
await shot(p, 'mention')
const idx = await p.$$eval('.mention-menu .mm-item', (els) => els.findIndex((e) => e.textContent.includes('TodoList') && e.textContent.includes('class')))
await p.$$eval('.mention-menu .mm-item', (els, i) => els[i].dispatchEvent(new MouseEvent('mousedown', { bubbles: true })), idx)
await p.waitForSelector('.aw-pane .chip-symbol')
await p.keyboard.type(' and @src')
await p.waitForSelector('.mention-menu .mm-sep:has-text("Folders")')
await p.keyboard.press('ArrowDown')
const folderIdx = await p.$$eval('.mention-menu .mm-item', (els) => els.findIndex((e) => e.dataset.type === 'folder' && e.dataset.value === 'src/'))
await p.$$eval('.mention-menu .mm-item', (els, i) => els[i].dispatchEvent(new MouseEvent('mousedown', { bubbles: true })), folderIdx)
await p.waitForSelector('.aw-pane .chip-folder')
ok(true, 'symbol and folder chips added')
await p.keyboard.press('Enter')
await p.waitForFunction(() => document.querySelector('.aw-pane .msg-user')?.textContent.includes('Symbol `TodoList`'), null, { timeout: 10000 })
ok(true, 'mentions expanded into structured context in the prompt')
await p.waitForSelector('.aw-pane .ctx-meter:not(.hidden)', { timeout: 20000 })
ok(true, 'context usage meter shown')
const id = (await api('/api/agents')).find((a) => a.title.startsWith('explain'))?.id
await p.waitForFunction(() => document.querySelector('.aw-item.selected .st-done'), null, { timeout: 20000 })
const c = await api(`/api/agents/${id}/compact`, 'POST')
ok(c.id === id, 'manual context compaction works')

ok(errors.length === 0, 'no page errors ' + errors.join('; '))
await b.close()
for (const pr of await api('/api/processes')) await api('/api/processes/' + pr.id, 'DELETE')
console.log('\nALL V2 E2E CHECKS PASSED')
